-- Blood & Sand schema. Compatible with PostgreSQL 10+ (identity columns, no gen_random_uuid, no generated columns).

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          TEXT        NOT NULL,
    password_hash  TEXT        NOT NULL,
    full_name      TEXT        NOT NULL,
    phone          TEXT        NOT NULL DEFAULT '',
    role           TEXT        NOT NULL CHECK (role IN ('admin', 'coach', 'student')),
    active         BOOLEAN     NOT NULL DEFAULT TRUE,
    last_login_at  TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_key ON users (lower(email));
CREATE INDEX users_role_idx ON users (role);

CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  TEXT        NOT NULL UNIQUE,
    family      TEXT        NOT NULL,
    expires_at  TIMESTAMPTZ NOT NULL,
    revoked_at  TIMESTAMPTZ,
    user_agent  TEXT        NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX refresh_tokens_user_idx ON refresh_tokens (user_id);
CREATE INDEX refresh_tokens_family_idx ON refresh_tokens (family);

CREATE TABLE disciplines (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug          TEXT    NOT NULL UNIQUE,
    name          TEXT    NOT NULL,
    tagline       TEXT    NOT NULL DEFAULT '',
    short         TEXT    NOT NULL DEFAULT '',
    description   TEXT    NOT NULL DEFAULT '',
    duration_min  INTEGER NOT NULL CHECK (duration_min BETWEEN 10 AND 240),
    price         BIGINT  NOT NULL DEFAULT 0 CHECK (price >= 0),
    image         TEXT    NOT NULL DEFAULT '',
    uses_credit   BOOLEAN NOT NULL DEFAULT TRUE,
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    sort          INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE plans (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug                 TEXT    NOT NULL UNIQUE,
    name                 TEXT    NOT NULL,
    price                BIGINT  NOT NULL CHECK (price >= 0),
    period_days          INTEGER NOT NULL DEFAULT 30 CHECK (period_days > 0),
    credits              INTEGER CHECK (credits IS NULL OR credits > 0), -- NULL = unlimited
    booking_window_days  INTEGER NOT NULL DEFAULT 14,
    perks                TEXT[]  NOT NULL DEFAULT '{}',
    featured             BOOLEAN NOT NULL DEFAULT FALSE,
    sellable             BOOLEAN NOT NULL DEFAULT TRUE, -- false = shown as info only (e.g. drop-in class)
    active               BOOLEAN NOT NULL DEFAULT TRUE,
    sort                 INTEGER NOT NULL DEFAULT 0
);

-- Weekly timetable managed by the admin
CREATE TABLE class_templates (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discipline_id  BIGINT   NOT NULL REFERENCES disciplines (id),
    coach_id       BIGINT   REFERENCES users (id) ON DELETE SET NULL,
    weekday        SMALLINT NOT NULL CHECK (weekday BETWEEN 1 AND 7), -- 1 = Monday
    start_time     TIME     NOT NULL,
    capacity       INTEGER  NOT NULL CHECK (capacity > 0),
    active         BOOLEAN  NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Concrete classes, generated from templates or created one-off
CREATE TABLE class_sessions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id    BIGINT      REFERENCES class_templates (id) ON DELETE SET NULL,
    discipline_id  BIGINT      NOT NULL REFERENCES disciplines (id),
    coach_id       BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    starts_at      TIMESTAMPTZ NOT NULL,
    ends_at        TIMESTAMPTZ NOT NULL,
    capacity       INTEGER     NOT NULL CHECK (capacity > 0),
    status         TEXT        NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled', 'cancelled')),
    note           TEXT        NOT NULL DEFAULT '',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (ends_at > starts_at)
);
CREATE UNIQUE INDEX class_sessions_template_start_key ON class_sessions (template_id, starts_at) WHERE template_id IS NOT NULL;
CREATE INDEX class_sessions_starts_idx ON class_sessions (starts_at);
CREATE INDEX class_sessions_coach_idx ON class_sessions (coach_id, starts_at);

CREATE TABLE memberships (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    plan_id        BIGINT      REFERENCES plans (id) ON DELETE SET NULL,
    plan_name      TEXT        NOT NULL,
    credits_total  INTEGER,
    credits_left   INTEGER CHECK (credits_left IS NULL OR credits_left >= 0),
    starts_at      TIMESTAMPTZ NOT NULL,
    ends_at        TIMESTAMPTZ NOT NULL,
    status         TEXT        NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'cancelled')),
    order_id       BIGINT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX memberships_user_idx ON memberships (user_id, status, ends_at);

CREATE TABLE orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_token  TEXT        NOT NULL UNIQUE, -- lets a guest check their own order
    user_id       BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    kind          TEXT        NOT NULL CHECK (kind IN ('plan', 'class')),
    plan_id       BIGINT      REFERENCES plans (id) ON DELETE SET NULL,
    booking_id    BIGINT,
    description   TEXT        NOT NULL,
    amount        BIGINT      NOT NULL CHECK (amount > 0),
    currency      TEXT        NOT NULL DEFAULT 'CLP',
    status        TEXT        NOT NULL DEFAULT 'pending'
                  CHECK (status IN ('pending', 'paid', 'failed', 'cancelled', 'expired', 'refunded')),
    provider      TEXT        NOT NULL,
    provider_ref  TEXT        NOT NULL DEFAULT '',
    buyer_name    TEXT        NOT NULL,
    buyer_email   TEXT        NOT NULL,
    buyer_phone   TEXT        NOT NULL DEFAULT '',
    detail        JSONB       NOT NULL DEFAULT '{}',
    paid_at       TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX orders_status_idx ON orders (status, created_at DESC);
CREATE INDEX orders_user_idx ON orders (user_id, created_at DESC);
CREATE INDEX orders_provider_ref_idx ON orders (provider, provider_ref);

CREATE TABLE bookings (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              TEXT        NOT NULL UNIQUE,
    session_id        BIGINT      NOT NULL REFERENCES class_sessions (id) ON DELETE CASCADE,
    user_id           BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    name              TEXT        NOT NULL,
    email             TEXT        NOT NULL,
    phone             TEXT        NOT NULL DEFAULT '',
    status            TEXT        NOT NULL
                      CHECK (status IN ('pending_payment', 'confirmed', 'cancelled', 'attended', 'no_show')),
    payment           TEXT        NOT NULL CHECK (payment IN ('free', 'plan', 'paid', 'staff')),
    membership_id     BIGINT      REFERENCES memberships (id) ON DELETE SET NULL,
    order_id          BIGINT      REFERENCES orders (id) ON DELETE SET NULL,
    amount            BIGINT      NOT NULL DEFAULT 0,
    notes             TEXT        NOT NULL DEFAULT '',
    created_by        BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    hold_expires_at   TIMESTAMPTZ,
    reminder_sent_at  TIMESTAMPTZ,
    cancelled_at      TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- One active booking per person per class
CREATE UNIQUE INDEX bookings_session_user_key ON bookings (session_id, user_id)
    WHERE user_id IS NOT NULL AND status IN ('pending_payment', 'confirmed', 'attended');
CREATE UNIQUE INDEX bookings_session_email_key ON bookings (session_id, lower(email))
    WHERE status IN ('pending_payment', 'confirmed', 'attended');
CREATE INDEX bookings_session_idx ON bookings (session_id, status);
CREATE INDEX bookings_user_idx ON bookings (user_id);
CREATE INDEX bookings_email_idx ON bookings (lower(email));

ALTER TABLE orders ADD CONSTRAINT orders_booking_fk FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE SET NULL;
ALTER TABLE memberships ADD CONSTRAINT memberships_order_fk FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE SET NULL;

CREATE TABLE push_subscriptions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      REFERENCES users (id) ON DELETE CASCADE,
    email         TEXT        NOT NULL DEFAULT '', -- guests subscribe with the email they booked with
    endpoint      TEXT        NOT NULL UNIQUE,
    p256dh        TEXT        NOT NULL,
    auth          TEXT        NOT NULL,
    user_agent    TEXT        NOT NULL DEFAULT '',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at  TIMESTAMPTZ
);
CREATE INDEX push_subscriptions_user_idx ON push_subscriptions (user_id);
CREATE INDEX push_subscriptions_email_idx ON push_subscriptions (lower(email));

CREATE TABLE announcements (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       TEXT        NOT NULL,
    body        TEXT        NOT NULL,
    url         TEXT        NOT NULL DEFAULT '/',
    audience    TEXT        NOT NULL CHECK (audience IN ('all', 'students', 'coaches')),
    sent_count  INTEGER     NOT NULL DEFAULT 0,
    created_by  BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
